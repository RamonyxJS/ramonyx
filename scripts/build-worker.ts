// Build artefak Cloudflare Worker:
//   1. ekspor docs + client root (docs/public) ke apps/docs/dist/static
//   2. edge build landing-only (streaming + custom document + asset map)
//   3. generate wrapper Worker: "/" → landing, sisanya static assets
//
// Jalankan: `pnpm build:worker`
import { execFileSync } from "node:child_process";
import { mkdir, writeFile } from "node:fs/promises";
import { join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { buildEdge } from "@ramonyx/bundler";

import { CONTEXT7_LINK } from "../apps/docs/src/context7.ts";

const root = fileURLToPath(new URL("..", import.meta.url));
const appDir = join(root, "apps/docs");
const origin = process.env.WORKER_ORIGIN ?? "https://ramonyx.devmoon.net";

console.log(`→ ekspor docs root (${origin})…`);
execFileSync(
  process.execPath,
  ["--import", join(root, "tools/register.mjs"), join(appDir, "export.ts"), "--origin", origin],
  { cwd: root, stdio: "inherit", env: { ...process.env, NODE_ENV: "production" } },
);

console.log("→ edge build landing-only…");
const edge = await buildEdge({
  appDir,
  pagePaths: ["/"],
  apiPaths: [],
  document: "src/edge-document.ts",
  streaming: true,
  clientLoad: "interaction",
  clientBootstrap:
    'try{const t=localStorage.getItem("ramonyx-theme");if(t==="light"||t==="dark")document.documentElement.dataset.theme=t}catch{};document.addEventListener("click",function(e){if(document.documentElement.classList.contains("hydrated"))return;const b=e.target instanceof Element?e.target.closest("[data-theme-toggle]"):null;if(!b)return;const d=document.documentElement;const n=d.dataset.theme==="dark"?"light":"dark";d.dataset.theme=n;try{localStorage.setItem("ramonyx-theme",n)}catch{}},true);',
});
console.log(`✓ edge: ${relative(root, edge.outputFile)} (${(edge.bytes / 1024).toFixed(1)} KB)`);

const workerDir = join(appDir, "dist/worker");
await mkdir(workerDir, { recursive: true });
const workerFile = join(workerDir, "index.js");
const edgeImport = relative(workerDir, edge.outputFile).split(sep).join("/");
const specifier = edgeImport.startsWith(".") ? edgeImport : `./${edgeImport}`;
const cacheVersion = Date.now().toString(36);
const wrapper = `// Generated by scripts/build-worker.ts — jangan diedit manual.
import landing from ${JSON.stringify(specifier)};

const CONTEXT7_LINK = ${JSON.stringify(CONTEXT7_LINK)};
const CACHE_VERSION = ${JSON.stringify(cacheVersion)};
const cache = caches.default;

async function fetchLanding(request, env, ctx) {
  const key = new Request(new URL(\`/?__ramonyx_cache=\${CACHE_VERSION}\`, request.url).toString(), {
    method: "GET",
  });
  const hit = await cache.match(key);
  if (hit) {
    const headers = new Headers(hit.headers);
    headers.set("x-ramonyx-cache", "HIT");
    return new Response(hit.body, { status: hit.status, headers });
  }
  const response = await landing.fetch(request, env);
  const headers = new Headers(response.headers);
  headers.set("cache-control", "public, max-age=60, s-maxage=60, stale-while-revalidate=300");
  headers.set("x-ramonyx-cache", "MISS");
  // Buffer HTML kecil (landing) agar Cache API dapat menyimpannya andal; request pertama
  // tetap SSR, request berikutnya dilayani dari edge cache.
  const body = await response.text();
  const cached = new Response(body, { status: response.status, headers });
  ctx.waitUntil(cache.put(key, cached.clone()).catch(() => undefined));
  return cached;
}

async function refreshStars(env) {
  try {
    const token = env.GITHUB_TOKEN;
    const response = await fetch("https://api.github.com/repos/RamonyxJS/ramonyx", {
      headers: {
        accept: "application/vnd.github+json",
        "user-agent": "ramonyx-site",
        ...(token === undefined ? {} : { authorization: \`Bearer \${token}\` }),
      },
    });
    if (!response.ok) return;
    const data = await response.json();
    if (typeof data.stargazers_count === "number" && env.WAITLIST) {
      await env.WAITLIST.put("meta:stars", String(data.stargazers_count));
    }
  } catch {
    // cache dibiarkan; cron berikutnya mencoba lagi
  }
}

export default {
  /**
   * Worker: landing SSR + action di "/", sisanya static assets docs.
   * @param {Request} request
   * @param {{ ASSETS: { fetch(request: Request): Promise<Response> }, WAITLIST?: { put(key: string, value: string): Promise<void> }, GITHUB_TOKEN?: string }} env
   */
  async fetch(request, env, ctx) {
    const url = new URL(request.url);
    if (url.pathname === "/" || url.pathname === "") {
      if (request.method === "HEAD") {
        const response = await fetchLanding(new Request(request, { method: "GET" }), env, ctx);
        return new Response(null, { status: response.status, headers: response.headers });
      }
      if (request.method === "GET") {
        return fetchLanding(request, env, ctx);
      }
      return landing.fetch(request, env);
    }
    // Worker Assets mengalihkan /docs → /docs/ (307). Context7 dan pengecekan curl
    // mengharapkan HTML langsung di /docs; layani index-nya tanpa redirect.
    const docsIndex =
      url.pathname === "/docs" || url.pathname === "/dokumen"
        ? new URL(url.pathname + "/", request.url)
        : null;
    const assetRequest =
      docsIndex === null
        ? request
        : new Request(docsIndex, { method: request.method, headers: request.headers });
    const response = await env.ASSETS.fetch(assetRequest);
    const headers = new Headers(response.headers);
    headers.set("x-content-type-options", "nosniff");
    headers.set("referrer-policy", "strict-origin-when-cross-origin");
    headers.set("x-frame-options", "DENY");
    if (
      url.pathname === "/docs" ||
      url.pathname.startsWith("/docs/") ||
      url.pathname === "/dokumen" ||
      url.pathname.startsWith("/dokumen/")
    ) {
      const existing = headers.get("link");
      headers.set("link", existing === null ? CONTEXT7_LINK : \`\${existing}, \${CONTEXT7_LINK}\`);
    }
    return new Response(response.body, { status: response.status, headers });
  },
  async scheduled(_event, env, ctx) {
    ctx.waitUntil(refreshStars(env));
  },
};
`;
await writeFile(workerFile, wrapper);
console.log(`✓ worker: ${relative(root, workerFile)}`);
console.log("✓ siap deploy: pnpm dlx wrangler deploy");
